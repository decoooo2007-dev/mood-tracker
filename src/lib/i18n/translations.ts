export type Locale = keyof typeof translations;
export type TranslationKey = keyof typeof translations.en;

// Current locale - read from localStorage on client
function getInitialLocale(): Locale {
  if (typeof window !== "undefined") {
    const stored = localStorage.getItem("moodflow-locale");
    if (stored === "en" || stored === "ar") {
      return stored;
    }
  }
  return "en";
}

// Initialize with stored locale or default
export let currentLocale: Locale = "en";

// Initialize on first access (client-side only)
if (typeof window !== "undefined") {
  currentLocale = getInitialLocale();
}

// Translation function
export function t(key: TranslationKey): string {
  return translations[currentLocale][key] || translations.en[key] || key;
}

// Set locale function
export function setLocale(locale: Locale) {
  currentLocale = locale;
  if (typeof window !== "undefined") {
    localStorage.setItem("moodflow-locale", locale);
  }
}

// Get direction based on locale
export function getDirection(): "ltr" | "rtl" {
  return currentLocale === "ar" ? "rtl" : "ltr";
}

// Get document direction attribute
export function getDirAttr(): { dir: "ltr" | "rtl" } {
  return { dir: getDirection() };
}

// Translate mood labels
export function tmood(mood: string): string {
  const key = `mood.${mood.toLowerCase()}` as TranslationKey;
  const translated = translations[currentLocale][key];
  return translated || mood;
}

// Translate tag labels
export function ttag(tag: string, locale: Locale = currentLocale): string {
  const key = `tag.${tag.trim().toLowerCase()}` as TranslationKey;
  return translations[locale]?.[key] || translations.en?.[key] || tag;
}

